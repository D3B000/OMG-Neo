"""Copy the skill's open SVG curves into dependency-free Flutter path data."""
from pathlib import Path
import xml.etree.ElementTree as ET

project = Path(__file__).resolve().parents[1]
source = project.parent / 'endfield-ui-skill-main' / 'assets' / 'contours'
lines = ['// Generated by tools/generate_contours.py from the endfield-ui skill.',
         '// Original open contours; coordinates are kept in SVG viewBox units.']
for name in ('a', 'b'):
    tree = ET.parse(source / f'contour-{name}.svg')
    paths = tree.findall('.//{http://www.w3.org/2000/svg}path')
    for index, path in enumerate(paths):
        lines.append(f"const contour{name.upper()}{index} = '{path.attrib['d']}';")
(project / 'lib' / 'ef' / 'contour_data.dart').write_text('\n'.join(lines) + '\n', encoding='utf-8')
